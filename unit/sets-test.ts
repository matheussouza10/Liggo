import { evaluateSets, invalidSetReason, liveState, maxSets, pointTotals, ratio, setTarget, setWinner, type SetsConfig } from "../src/lib/competition/sets";
let f=0; const ok=(n:string,c:boolean)=>{ if(!c) f++; console.log(c?"PASS":"FAIL",n) };
const vb:SetsConfig={setsToWin:3,pointsPerSet:25,decidingSetPoints:15,winByTwo:true};
const tt:SetsConfig={setsToWin:3,pointsPerSet:11,decidingSetPoints:11,winByTwo:true};
const bm:SetsConfig={setsToWin:2,pointsPerSet:21,decidingSetPoints:21,winByTwo:true};
const nb:SetsConfig={setsToWin:2,pointsPerSet:15,decidingSetPoints:15,winByTwo:false};
ok("máximo de sets: bo5=5, bo3=3",maxSets(vb)===5&&maxSets(bm)===3);
ok("alvo: 25 nos sets normais, 15 no decisivo (2x2)",setTarget(vb,0,0)===25&&setTarget(vb,2,1)===25&&setTarget(vb,2,2)===15);
ok("em bo3 o decisivo é o 3º (1x1)",setTarget(bm,1,1)===21&&setTarget(bm,1,0)===21);
ok("25-23 vale",invalidSetReason(vb,25,{home:25,away:23})===null);
ok("25-24 não vale (diferença de 1)",!!invalidSetReason(vb,25,{home:25,away:24}));
ok("26-24 vale (prolongamento)",invalidSetReason(vb,25,{home:26,away:24})===null);
ok("27-24 não vale (terminou antes)",!!invalidSetReason(vb,25,{home:27,away:24}));
ok("24-22 não vale (não chegou ao alvo)",!!invalidSetReason(vb,25,{home:24,away:22}));
ok("15-13 no set decisivo vale",invalidSetReason(vb,15,{home:15,away:13})===null);
ok("30-28 vale, 30-27 não",invalidSetReason(vb,25,{home:30,away:28})===null&&!!invalidSetReason(vb,25,{home:30,away:27}));
ok("negativo e decimal recusados",!!invalidSetReason(vb,25,{home:-1,away:25})&&!!invalidSetReason(vb,25,{home:25.5,away:20}));
ok("sem diferença de 2: 15-14 vale, 16-14 não",invalidSetReason(nb,15,{home:15,away:14})===null&&!!invalidSetReason(nb,15,{home:16,away:14}));
ok("tênis de mesa 11-9 vale e 12-10 vale",invalidSetReason(tt,11,{home:11,away:9})===null&&invalidSetReason(tt,11,{home:12,away:10})===null);
ok("setWinner: em andamento 24-24 é nulo, 26-24 é casa",setWinner(vb,25,{home:24,away:24})===null&&setWinner(vb,25,{home:26,away:24})==="HOME");
let r=evaluateSets(vb,[{home:25,away:20},{home:25,away:22},{home:25,away:18}]);
ok("3-0 completo, casa vence",r.complete&&r.winner==="HOME"&&r.homeSets===3&&r.awaySets===0&&!r.error);
r=evaluateSets(vb,[{home:25,away:20},{home:20,away:25},{home:25,away:22},{home:23,away:25},{home:15,away:13}]);
ok("3-2 com set decisivo a 15",r.complete&&r.winner==="HOME"&&r.homeSets===3&&r.awaySets===2&&!r.error);
r=evaluateSets(vb,[{home:25,away:20},{home:20,away:25},{home:25,away:22},{home:23,away:25},{home:25,away:20}]);
ok("5º set decisivo a 25-20 é recusado (passou de 15 sem ser por 2)",!!r.error&&/5/.test(r.error));
r=evaluateSets(vb,[{home:25,away:20},{home:25,away:22}]);
ok("2-0 ainda não terminou",!r.complete&&r.winner===null&&!r.error);
r=evaluateSets(vb,[{home:25,away:20},{home:25,away:22},{home:25,away:18},{home:25,away:10}]);
ok("set depois do fim é recusado",!!r.error);
r=evaluateSets(vb,[{home:25,away:24}]);
ok("set inválido aponta o número",!!r.error&&r.error.startsWith("Set 1"));
r=evaluateSets(bm,[{home:21,away:19},{home:18,away:21},{home:21,away:23}]);
ok("badminton 1-2 visitante vence",r.complete&&r.winner==="AWAY"&&r.awaySets===2);
r=evaluateSets(vb,[]);
ok("vazio não está completo",!r.complete&&!r.error);
let l=liveState(vb,[{home:12,away:9}]);
ok("ao vivo: set em andamento, alvo 25",l.current.home===12&&l.homeSets===0&&l.target===25&&!l.complete);
l=liveState(vb,[{home:25,away:20},{home:3,away:1}]);
ok("ao vivo: 1 set fechado e o segundo em andamento",l.finished.length===1&&l.homeSets===1&&l.current.home===3);
l=liveState(vb,[{home:25,away:20},{home:23,away:25},{home:25,away:22},{home:21,away:25},{home:14,away:14}]);
ok("ao vivo: decisivo 14-14 segue, alvo 15",l.homeSets===2&&l.awaySets===2&&l.target===15&&l.current.home===14&&!l.complete);
l=liveState(vb,[{home:25,away:20},{home:23,away:25},{home:25,away:22},{home:21,away:25},{home:15,away:14}]);
ok("ao vivo: decisivo 15-14 ainda não fecha (precisa de 2)",!l.complete&&l.current.home===15);
l=liveState(vb,[{home:25,away:20},{home:23,away:25},{home:25,away:22},{home:21,away:25},{home:16,away:14}]);
ok("ao vivo: 16-14 fecha o jogo",l.complete&&l.homeSets===3);
l=liveState(vb,[{home:25,away:20},{home:25,away:10},{home:25,away:0}]);
ok("ao vivo: 3-0 fecha, atual zerado",l.complete&&l.current.home===0&&l.current.away===0);
ok("totais de pontos",JSON.stringify(pointTotals([{home:25,away:20},{home:18,away:25}]))==='{"home":43,"away":45}');
ok("razão: 6/3=2, sem derrotas é infinito, 0/0 é 0",ratio(6,3)===2&&ratio(5,0)===Infinity&&ratio(0,0)===0);
r=evaluateSets(vb,[{home:25,away:20},{home:20,away:25},{home:25,away:22},{home:23,away:25},{home:25,away:23}]);
ok("decisivo prolongado 25-23 é válido",r.complete&&r.winner==="HOME"&&!r.error);
console.log(f===0?"TODOS PASSARAM":`${f} FALHAS`);
