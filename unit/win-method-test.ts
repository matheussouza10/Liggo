import { isCombatSport, podiumOf, WIN_METHODS, WIN_METHOD_LABELS } from "../src/lib/competition/win-method";
let f=0; const ok=(n:string,c:boolean)=>{ if(!c) f++; console.log(c?"PASS":"FAIL",n) };
const m=(label:string,h:string|null,a:string|null,w:string|null)=>({label,homeId:h,awayId:a,winnerId:w});
ok("todo método tem rótulo",WIN_METHODS.every(k=>!!WIN_METHOD_LABELS[k]));
ok("modalidade de luta reconhecida pela categoria",isCombatSport("Artes marciais e lutas")&&!isCombatSport("Esportes coletivos")&&!isCombatSport(null));
const semis=[m("Semifinal","a","d","a"),m("Semifinal","b","c","c")];
let p=podiumOf([...semis,m("Final","a","c","c"),m("Disputa de 3º lugar","d","b","b")],{double:false,sharedBronze:false});
ok("mata-mata com disputa de 3º: campeão c, vice a, 3º b",p.map(x=>`${x.place}${x.id}`).join()==="1c,2a,3b");
p=podiumOf([...semis,m("Final","a","c","c")],{double:false,sharedBronze:true});
ok("luta sem disputa de 3º: dois bronzes (os perdedores das semifinais d e b)",p.filter(x=>x.place===3).map(x=>x.id).sort().join()==="b,d"&&p.filter(x=>x.place===3).every(x=>x.note==="Bronze"));
p=podiumOf([...semis,m("Final","a","c","c")],{double:false,sharedBronze:false});
ok("sem disputa de 3º e sem bronze duplo: só campeão e vice",p.length===2);
p=podiumOf([...semis,m("Final","a","c",null)],{double:false,sharedBronze:true});
ok("final sem resultado: sem pódio",p.length===0);
p=podiumOf([m("Semifinal da chave superior","a","b","a"),m("Final da chave inferior","c","b","c"),m("Final","a","c","c")],{double:true,sharedBronze:false});
ok("dupla eliminação: campeão c, vice a, 3º b (perdeu a final da inferior)",p.map(x=>`${x.place}${x.id}`).join()==="1c,2a,3b");
p=podiumOf([m("Final da chave inferior","c","b","c"),m("Final","a","c","c"),m("Final decisiva","a","c",null)],{double:true,sharedBronze:false});
ok("final com jogo extra pendente: sem pódio ainda",p.length===0);
p=podiumOf([m("Final da chave inferior","c","b","c"),m("Final","a","c","c"),m("Final decisiva","a","c","a")],{double:true,sharedBronze:false});
ok("a decisiva define campeão (a) e vice (c)",p[0].id==="a"&&p[1].id==="c"&&p[2].id==="b");
console.log(f===0?"TODOS PASSARAM":`${f} FALHAS`);
