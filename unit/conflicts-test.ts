import { findConflicts, type ScheduledGame } from "../src/lib/competition/schedule-conflicts";
let f=0; const ok=(n:string,c:boolean)=>{ if(!c) f++; console.log(c?"PASS":"FAIL",n) };
const T0=Date.UTC(2026,11,5,13,0), MIN=60000;
const g=(id:string,min:number,o:Partial<ScheduledGame>={}):ScheduledGame=>({id,at:T0+min*MIN,venue:"Quadra 1",refereeId:null,sides:[id+"a",id+"b"],athletes:[],...o});
ok("sem problemas: nenhum conflito",findConflicts([g("1",0),g("2",0,{venue:"Quadra 2"}),g("3",60)]).length===0);
let c=findConflicts([g("1",0),g("2",0)]);
ok("mesmo local e mesmo horário",c.length===1&&c[0].kind==="venue");
ok("o nome do local ignora caixa e acento",findConflicts([g("1",0,{venue:"Ginásio Térreo"}),g("2",0,{venue:"ginasio terreo"})]).some(x=>x.kind==="venue"));
c=findConflicts([g("1",0,{venue:"A",refereeId:"r1"}),g("2",0,{venue:"B",refereeId:"r1"})]);
ok("mesmo árbitro no mesmo horário",c.length===1&&c[0].kind==="referee");
c=findConflicts([g("1",0,{venue:"A",sides:["x","y"]}),g("2",0,{venue:"B",sides:["z","x"]})]);
ok("o mesmo time em dois jogos ao mesmo tempo",c.length===1&&c[0].kind==="side");
c=findConflicts([g("1",0,{venue:"A",athletes:["p1","p2"]}),g("2",0,{venue:"B",athletes:["p9","p1"]})]);
ok("o mesmo atleta (de times diferentes) em dois jogos ao mesmo tempo",c.length===1&&c[0].kind==="athlete");
c=findConflicts([g("1",0,{sides:["x","y"]}),g("2",15,{venue:"B",sides:["x","z"]})]);
ok("o mesmo time com 15 minutos de intervalo gera aviso de descanso curto",c.length===1&&c[0].kind==="rest");
ok("com 30 minutos ou mais de intervalo não há aviso",findConflicts([g("1",0,{sides:["x","y"]}),g("2",30,{venue:"B",sides:["x","z"]})]).length===0);
ok("o intervalo mínimo é configurável",findConflicts([g("1",0,{sides:["x","y"]}),g("2",45,{venue:"B",sides:["x","z"]})],{restMinutes:60}).length===1);
ok("jogos de times diferentes em horários próximos não geram descanso curto",findConflicts([g("1",0),g("2",10,{venue:"B"})]).length===0);
c=findConflicts([g("1",0),g("2",0),g("3",0)]);
ok("três jogos no mesmo local e horário: 3 pares",c.filter(x=>x.kind==="venue").length===3);
ok("entrada em qualquer ordem dá o mesmo resultado",findConflicts([g("2",0),g("1",0)]).length===1);
ok("local vazio não conflita",findConflicts([g("1",0,{venue:null}),g("2",0,{venue:null})]).length===0);
console.log(f===0?"TODOS PASSARAM":`${f} FALHAS`);
